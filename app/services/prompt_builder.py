class PromptBuilder:
    @staticmethod
    def _messages(
        instructions: str, payload: dict[str, Any], character: dict[str, Any] | None = None,
    ) -> list[dict[str, str]]:
        messages = [{"role": "system", "content": instructions}]
        if character is not None:
            messages.append({
                "role": "user",
                "content": json.dumps({"character_profile": character}, ensure_ascii=False),
            })
        messages.append({"role": "user", "content": json.dumps(payload, ensure_ascii=False)})
        return messages

    def build_neutral(self, subject: dict[str, Any], natal_xml: str) -> list[dict[str, str]]:
        return self._messages(NEUTRAL_INSTRUCTIONS, {"subject": subject, "natal_xml": natal_xml})

    def build_intro(
        self, character: dict[str, Any], subject: dict[str, Any], block: Block
    ) -> list[dict[str, str]]:
        return self._messages(WRITER_INSTRUCTIONS, {
            "task": INTRO_INSTRUCTIONS,
            "subject": subject,
            "current_block": block.model_dump(mode="json"),
        }, character)

    def build_style_plan(
        self, character: dict[str, Any], block: Block,
        previous_blocks: dict[str, CharacterBlockResult],
    ) -> list[dict[str, str]]:
        return self._messages(PLAN_INSTRUCTIONS, {
            "current_block": block.model_dump(mode="json"),
            "previous_blocks": {key: value.model_dump(mode="json") for key, value in previous_blocks.items()},
            "allowed_enums": {
                "emotion": list(CharacterEmotion),
                "humor_types": list(HumorType),
                "speech_patterns": list(SpeechPattern),
            },
        }, character)

    def build_block(
        self, character: dict[str, Any], subject: dict[str, Any], block: Block,
        plan: BlockStylePlan, previous_blocks: dict[str, CharacterBlockResult],
    ) -> list[dict[str, str]]:
        return self._messages(WRITER_INSTRUCTIONS, {
            "task": BLOCK_INSTRUCTIONS,
            "subject": subject,
            "current_block": block.model_dump(mode="json"),
            "style_plan": plan.model_dump(mode="json"),
            "previous_blocks": {key: value.model_dump(mode="json") for key, value in previous_blocks.items()},
        }, character)
